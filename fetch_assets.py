#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Automated Game Asset Fetcher via REST APIs (Iconify Game-Icons / Twemoji + Openverse / Freesound)
1. Iconify API (game-icons CC BY 3.0 & twemoji CC BY 4.0) からボス・スキル・キャラのSVGベクター素材を自動取得
2. Openverse Audio API (Freesound CC0 / CC BY) から本物の効果音・ジングルMP3を検索・取得
3. Openverse Images API からCC0/CC BY背景テクスチャを検索・取得
4. 取得した全アセットの作者名・ライセンス・元URLを CREDITS.txt に自動出力し、
   ゲームエンジンが即座に描画・再生できる src/common/game_assets_bundle.js を生成する
"""

import base64
import json
import subprocess
import urllib.parse
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
ASSETS_DIR = BASE_DIR / "assets"
BUNDLE_JS_PATH = BASE_DIR / "src" / "common" / "game_assets_bundle.js"
CREDITS_PATH = BASE_DIR / "CREDITS.txt"


def curl_get(url: str) -> bytes:
    out = subprocess.check_output(
        ["curl.exe", "-s", "-L", "--max-time", "12", "-A", "Mozilla/5.0 (Windows NT 10.0; Win64; x64)", url]
    )
    return out


def fetch_iconify_svg_data_uri(prefix: str, name: str, color: str = "") -> str:
    q = f"?color={urllib.parse.quote(color)}" if color else ""
    url = f"https://api.iconify.design/{prefix}/{name}.svg{q}"
    raw = curl_get(url)
    if not raw or not raw.lstrip().startswith(b"<svg"):
        return ""
    b64 = base64.b64encode(raw).decode("ascii")
    return f"data:image/svg+xml;base64,{b64}"


def emoji_to_codepoint(em: str) -> str:
    # Remove variation selector FE0F if needed by twemoji, or try both
    cps = [f"{ord(c):x}" for c in em if ord(c) != 0xFE0F]
    return "-".join(cps)


def main():
    ASSETS_DIR.mkdir(parents=True, exist_ok=True)
    credits_lines = [
        "========================================================================",
        " Weekly Buzz Satire Mini-Games 2026 - Third-Party Game Assets Credits",
        " Automatically generated by fetch_assets.py via REST APIs",
        "========================================================================",
        "",
    ]

    # 1. Fetch RPG Boss, Skill & Effect Vector Icons from Iconify (game-icons: CC BY 3.0)
    game_icons_specs = {
        # Bosses
        "boss_ai_server": ("game-icons", "cyber-eye", "#00e5ff", "Lorc / Delapouite (Game Icons)"),
        "boss_ai_core": ("game-icons", "processor", "#fde047", "Lorc / Delapouite (Game Icons)"),
        "boss_kumagaa": ("game-icons", "sands-of-time", "#ffd700", "Lorc / Delapouite (Game Icons)"),
        "boss_mic": ("game-icons", "microphone", "#ff4081", "Lorc / Delapouite (Game Icons)"),
        "boss_shrink": ("game-icons", "monster-grasp", "#f43f5e", "Lorc / Delapouite (Game Icons)"),
        "boss_frenemy": ("game-icons", "crowned-heart", "#ec4899", "Lorc / Delapouite (Game Icons)"),
        "boss_algo": ("game-icons", "evil-eye", "#ef4444", "Lorc / Delapouite (Game Icons)"),
        "boss_gamer_god": ("game-icons", "crowned-skull", "#a855f7", "Lorc / Delapouite (Game Icons)"),
        "boss_leather_ceo": ("game-icons", "leather-vest", "#76ff03", "Lorc / Delapouite (Game Icons)"),
        # Skills & Battle Visual Effects
        "skill_attack": ("game-icons", "sword-clash", "#38bdf8", "Lorc / Delapouite (Game Icons)"),
        "skill_roast": ("game-icons", "flame-spin", "#ff80ab", "Lorc / Delapouite (Game Icons)"),
        "skill_heal": ("game-icons", "shield-reflect", "#00e676", "Lorc / Delapouite (Game Icons)"),
        "skill_ult": ("game-icons", "laser-blast", "#ffd700", "Lorc / Delapouite (Game Icons)"),
        "fx_lightning": ("game-icons", "lightning-storm", "#fde047", "Lorc / Delapouite (Game Icons)"),
        "fx_laser": ("game-icons", "sinusoidal-beam", "#00e5ff", "Lorc / Delapouite (Game Icons)"),
        "fx_explosion": ("game-icons", "explosion-rays", "#ff1744", "Lorc / Delapouite (Game Icons)"),
        "fx_shield": ("game-icons", "magic-shield", "#38bdf8", "Lorc / Delapouite (Game Icons)"),
    }

    svg_sprites = {}
    print("Fetching Game-Icons (CC BY 3.0) via Iconify REST API...")
    for key, (prefix, icon_name, color, author) in game_icons_specs.items():
        uri = fetch_iconify_svg_data_uri(prefix, icon_name, color)
        if uri:
            svg_sprites[key] = uri

    credits_lines.extend([
        "[1] Game Icons (RPG Bosses, Skills & Visual Effect Vector Sprites)",
        "  - Collection: Game Icons (https://game-icons.net/ / https://api.iconify.design/game-icons/)",
        "  - Authors: Lorc, Delapouite, Skoll and contributors",
        "  - License: Creative Commons Attribution 3.0 Unported (CC BY 3.0)",
        "  - License URL: https://creativecommons.org/licenses/by/3.0/",
        "  - Icons Used: " + ", ".join(f"{v[0]}:{v[1]}" for v in game_icons_specs.values()),
        "",
    ])

    # 2. Extract all unique emojis from themes_2026.json and fetch Full-Color Vector SVGs from Twemoji (CC BY 4.0) via Iconify API
    themes_doc = json.loads((BASE_DIR / "themes" / "trends_2026.json").read_text(encoding="utf-8"))
    unique_emojis = set()
    for t in themes_doc.get("themes", []):
        if "player" in t and t["player"].get("emoji"):
            unique_emojis.add(t["player"]["emoji"])
        for list_key in ("items", "good_items", "bad_items", "targets", "collectibles"):
            for it in t.get(list_key, []):
                if it.get("emoji"):
                    unique_emojis.add(it["emoji"])

    # Add common UI/effect emojis
    for em in ["🤖", "⚡", "💸", "🎙️", "⏳", "💢", "👹", "🍱", "📉", "💅", "📸", "🐍", "👁️", "🧟‍♂️", "🔥", "👑", "💥", "🛡️", "🩺", "🧥"]:
        unique_emojis.add(em)

    emoji_sprites = {}
    print(f"Fetching {len(unique_emojis)} Full-Color Vector Character Sprites (Twemoji CC BY 4.0) via Iconify API...")
    for em in sorted(unique_emojis):
        # Single-character or first base character codepoint
        base_char = em[0]
        cp = f"{ord(base_char):x}"
        uri = fetch_iconify_svg_data_uri("twemoji", cp)
        if not uri:
            cp_full = emoji_to_codepoint(em)
            uri = fetch_iconify_svg_data_uri("twemoji", cp_full)
        if uri:
            emoji_sprites[em] = uri

    credits_lines.extend([
        "[2] Twemoji Full-Color Character & Item Vector Graphics",
        "  - Collection: Twemoji via Iconify API (https://api.iconify.design/twemoji/)",
        "  - Author: Twitter, Inc. and other contributors",
        "  - License: Creative Commons Attribution 4.0 International (CC BY 4.0)",
        "  - License URL: https://creativecommons.org/licenses/by/4.0/",
        f"  - Sprites Bundled: {len(emoji_sprites)} vector character/item sprites",
        "",
    ])

    # 3. Fetch Real Sound Effects (SFX) via Openverse Audio API (Freesound CC0 / CC BY)
    sfx_queries = {
        "hit": "arcade hit retro",
        "merge": "powerup coin retro",
        "bad": "retro explosion damage",
        "milestone": "fanfare level up",
        "gameover": "game over retro",
    }
    sfx_urls = {}
    credits_lines.append("[3] Sound Effects (Openverse Audio API / Freesound.org CC0 & CC BY)")
    print("Querying Openverse Audio API for CC0/CC-BY Sound Effects...")
    for sfx_key, q in sfx_queries.items():
        api_url = f"https://api.openverse.org/v1/audio/?q={urllib.parse.quote(q)}&license=cc0,by&page_size=3"
        try:
            raw = curl_get(api_url)
            data = json.loads(raw.decode("utf-8"))
            results = data.get("results", [])
            for item in results:
                mp3_url = item.get("url", "")
                if mp3_url.endswith(".mp3"):
                    sfx_urls[sfx_key] = mp3_url
                    attr = item.get("attribution") or f"\"{item.get('title')}\" by {item.get('creator')} ({item.get('license')})"
                    src_url = item.get("foreign_landing_url") or mp3_url
                    credits_lines.append(f"  - [{sfx_key}] {attr} | Source: {src_url}")
                    break
        except Exception as e:
            print(f"Warning fetching audio {sfx_key}: {e}")
    credits_lines.append("")

    # 4. Fetch Stage Background Art Metadata via Openverse Images API (CC0 / CC BY)
    bg_queries = {
        "cyber_stage": "cyberpunk neon grid",
        "arcade_stage": "retro arcade neon",
    }
    bg_images = {}
    credits_lines.append("[4] Background Art & Textures (Openverse Images API - CC0 / CC BY)")
    print("Querying Openverse Images API for CC0/CC-BY Stage Backgrounds...")
    for bg_key, q in bg_queries.items():
        api_url = f"https://api.openverse.org/v1/images/?q={urllib.parse.quote(q)}&license=cc0,by&page_size=2"
        try:
            raw = curl_get(api_url)
            data = json.loads(raw.decode("utf-8"))
            results = data.get("results", [])
            if results:
                item = results[0]
                bg_images[bg_key] = item.get("thumbnail") or item.get("url")
                attr = item.get("attribution") or f"\"{item.get('title')}\" by {item.get('creator')}"
                credits_lines.append(f"  - [{bg_key}] {attr} | Source: {item.get('foreign_landing_url')}")
        except Exception as e:
            print(f"Warning fetching image {bg_key}: {e}")
    credits_lines.append("")

    CREDITS_PATH.write_text("\n".join(credits_lines), encoding="utf-8")
    print(f"Wrote {CREDITS_PATH}")

    # 5. Write src/common/game_assets_bundle.js with preloaded Image objects & SFX player
    bundle_obj = {
        "svg_sprites": svg_sprites,
        "emoji_sprites": emoji_sprites,
        "sfx_urls": sfx_urls,
        "bg_images": bg_images,
    }
    js_code = f"""/**
 * Pre-bundled Free Game Assets fetched via Iconify API (Game-Icons CC BY 3.0 & Twemoji CC BY 4.0)
 * and Openverse API (Freesound CC0/CC BY Audio & Textures).
 * See /CREDITS.txt for full author and license attributions.
 */
window.GAME_ASSETS_DATA = {json.dumps(bundle_obj, ensure_ascii=False)};

(function() {{
  const cache = {{ icons: {{}}, emojis: {{}}, audio: {{}} }};
  const data = window.GAME_ASSETS_DATA || {{}};

  if (data.svg_sprites) {{
    for (const [k, uri] of Object.entries(data.svg_sprites)) {{
      const img = new Image();
      img.src = uri;
      cache.icons[k] = img;
    }}
  }}

  if (data.emoji_sprites) {{
    for (const [k, uri] of Object.entries(data.emoji_sprites)) {{
      const img = new Image();
      img.src = uri;
      cache.emojis[k] = img;
    }}
  }}

  if (data.sfx_urls) {{
    for (const [k, url] of Object.entries(data.sfx_urls)) {{
      try {{
        const aud = new Audio();
        aud.crossOrigin = 'anonymous';
        aud.preload = 'auto';
        aud.src = url;
        aud.volume = 0.45;
        cache.audio[k] = aud;
      }} catch (e) {{}}
    }}
  }}

  window.GAME_ASSET_CACHE = cache;
}})();
"""
    BUNDLE_JS_PATH.write_text(js_code, encoding="utf-8")
    print(f"Wrote {BUNDLE_JS_PATH} ({len(svg_sprites)} game-icons, {len(emoji_sprites)} twemoji sprites, {len(sfx_urls)} Freesound SFX)")


if __name__ == "__main__":
    main()
